// Embed the voice preview clips as base64 strings.
const fs = require("fs");
const path = require("path");

const
    source = path.resolve(__dirname, "../src/assets/voices"),
    target = path.resolve(__dirname, "../src/speech/samples.ts"),
    voices = [
        ["female_1", "female_1.wav", "Female 1 preview"],
        ["female_2", "female_2.wav", "Female 2 preview"],
        ["male_1", "male_1.wav", "Male preview"],
        ["male_2", "male_2.wav", "Male 2 preview"],
    ],
    width = 88,
    wrap = (value) => {
        const lines = [];
        for (let i = 0; i < value.length; i += width) {
            lines.push(`        "${value.slice(i, i + width)}"`);
        }
        return lines.join(" +\n");
    },
    body = voices
        .map(([name, file, comment]) => {
            const base64 = fs
                .readFileSync(path.join(source, file))
                .toString("base64");
            return `    /** ${comment}. */\n    ${name} =\n${wrap(base64)}`;
        })
        .join(",\n"),
    output = `// Generated by scripts/embed-voice-samples.cjs. Do not edit.
// WAV 16 kHz mono 16 bit, bundled so a voice can be previewed before any
// model weight is downloaded.
const
${body};
export { female_1, female_2, male_1, male_2 };
`;

fs.writeFileSync(target, output);
console.log(`wrote ${path.relative(process.cwd(), target)}`);
