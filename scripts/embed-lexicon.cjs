// Generate src/speech/engines/lexicon.ts from the misaki US gold lexicon.
//
// Usage: node scripts/embed-lexicon.cjs <path to us_gold.json>
//
// The source is hexgrad/misaki (Apache-2.0). Entries are front-coded in
// sorted order: two base36 characters of shared prefix length, the new
// suffix, a tab, then the phoneme string. Only the DEFAULT reading of an
// ambiguous entry is kept because the package has no part-of-speech tagger.
const { readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const source = process.argv[2];
if (!source) {
    console.error("usage: embed-lexicon.cjs <us_gold.json>");
    process.exit(1);
}

const entries = [];
for (const [word, value] of Object.entries(JSON.parse(readFileSync(source, "utf8")))) {
    const phonemes = typeof value === "string" ? value : value.DEFAULT;
    if (!phonemes) {
        continue;
    }
    entries.push([word, phonemes]);
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

let previous = "";
const rows = [];
for (const [word, phonemes] of entries) {
    let shared = 0;
    while (shared < word.length && shared < previous.length &&
        word[shared] === previous[shared]) {
        shared += 1;
    }
    rows.push(`${shared.toString(36).padStart(2, "0")}${word.slice(shared)}\t${phonemes}`);
    previous = word;
}

const lines = [];
for (let i = 0; i < rows.length; i += 8) {
    lines.push(`        "${rows.slice(i, i + 8).join("\\n")}\\n",`);
}
const content = `// Generated by scripts/embed-lexicon.cjs. Do not edit.
// English IPA lexicon from hexgrad/misaki (Apache-2.0), front-coded:
// two base36 characters of shared prefix length, suffix, tab, phonemes.
const
    /** Front-coded lexicon chunks. */
    ROWS = [
${lines.join("\n")}
    ].join(""),
    /** Decode the rows into a word to phoneme map. */
    decode = (): Map<string, string> => {
        const map = new Map<string, string>();
        let previous = "";
        for (const row of ROWS.split("\\n")) {
            const tab = row.indexOf("\\t");
            const shared = parseInt(row.slice(0, 2), 36);
            const word = previous.slice(0, shared) + row.slice(2, tab);
            map.set(word, row.slice(tab + 1));
            previous = word;
        }
        return map;
    };

export { decode as decodeLexicon };
`;
writeFileSync(join(__dirname, "..", "src", "speech", "engines", "lexicon.ts"), content);
console.log(`wrote ${entries.length} entries, ${content.length} bytes`);
