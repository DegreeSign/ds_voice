// Embed one bundled voice pack GGUF as base64.
//
// Usage: node scripts/embed-voice-pack.cjs <pack.gguf> <export name>
const { readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const [source, name] = process.argv.slice(2);
if (!source || !name) {
    console.error("usage: embed-voice-pack.cjs <pack.gguf> <export name>");
    process.exit(1);
}

const text = readFileSync(source).toString("base64");
const chunks = [];
for (let i = 0; i < text.length; i += 8000) {
    chunks.push(`        "${text.slice(i, i + 8000)}",`);
}

const content = `// Generated by scripts/embed-voice-pack.cjs. Do not edit.
const
    /** Base64 chunks of the bundled voice pack. */
    ${name} = [
${chunks.join("\n")}
    ];

export { ${name} };
`;
writeFileSync(
    join(__dirname, "..", "src", "speech", "assets", "voicePacks.ts"),
    content,
);
console.log(`wrote ${text.length} base64 chars`);
